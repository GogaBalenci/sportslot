import { useEffect, useState } from 'react'
import QRCode from 'qrcode'
import { CheckInBox } from './BookingsTab'

const steps = [
  { title: 'Расписание', text: 'Во вкладке «Расписание» добавьте занятия, на которые берёте новичков, и сколько мест отдаёте. Сервис сам поддерживает расписание на две недели вперёд.' },
  { title: 'Новые записи', text: 'О каждой записи, отмене и подтверждении «Иду» приходит сообщение в бот. Имя клиента — ссылка на его профиль в MAX, кнопка «Открыть в кабинете» показывает карточку клиента.' },
  { title: 'На входе', text: 'Клиент показывает QR-пропуск. Нажмите «Сканировать QR-пропуск» во вкладке «Записи» и наведите камеру. Если камеры нет — введите 6 цифр кода.' },
  { title: 'После занятия', text: 'Клиент сразу получает вопрос «Как прошло?» и предложение записаться снова. Оценки и повторные записи видны в «Статистике».' },
  { title: 'Если занятие отменяется', text: 'В «Расписании» нажмите ⊘ у занятия. Все записавшиеся получат сообщение об отмене с телефоном студии. Чтобы временно не принимать записи, закройте запись замком.' },
  { title: 'Вопросы клиентов', text: 'Клиенты пишут студии из бота. Ответить можно во вкладке «Сообщения» — ответ придёт клиенту в чат.' },
]

// Инструкция и учебный пропуск: на нём администратор пробует сканер, не трогая реальных клиентов.
export function HelpTab() {
  const [qr, setQr] = useState('')
  useEffect(() => {
    QRCode.toDataURL('SPORTSLOT:000000', { margin: 1, width: 320, color: { dark: '#1A237E', light: '#FFFFFF' } }).then(setQr).catch(() => setQr(''))
  }, [])
  return (
    <>
      <section className="info-card">
        <h2 className="h2">Как работать с кабинетом</h2>
        <ol className="steps">
          {steps.map((s) => (
            <li key={s.title}><b>{s.title}.</b> {s.text}</li>
          ))}
        </ol>
      </section>
      <section className="info-card training">
        <h2 className="h2">Потренируйтесь на учебном пропуске</h2>
        <p className="muted">Откройте этот экран на одном устройстве, а сканер — на другом, или введите код <b>000 000</b> вручную. Настоящие записи не меняются.</p>
        {qr && <img className="training__qr" src={qr} alt="Учебный QR-пропуск" />}
        <CheckInBox />
      </section>
    </>
  )
}
